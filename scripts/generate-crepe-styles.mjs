/**
 * Build-time CSS bundler for @milkdown/crepe.
 *
 * Crepe ships its theme as a tree of `.css` files linked with relative/bare
 * `@import`s. The client bundle is a single `client.js` with no CSS sidecar, so
 * this script inlines the tree (in `@import` order), appends the `frame` theme
 * variables, then our DSH token overrides, and emits one JS module exporting
 * the whole stylesheet as a string.
 *
 * LaTeX is skipped on purpose: the feature is disabled and `katex.min.css`
 * points at font files that a single-file bundle cannot serve.
 */
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const root = path.resolve(import.meta.dirname, '..')
const output = path.join(root, 'client-src/editors/crepe-theme.generated.js')
const overrides = path.join(root, 'client-src/editors/dsh-crepe.css')

const commonEntry = require.resolve('@milkdown/crepe/theme/common/style.css')
const themeDir = path.dirname(commonEntry)
const frameEntry = require.resolve('@milkdown/crepe/theme/frame.css')
const IMPORT_RE = /@import\s+['"]([^'"]+)['"]\s*;?/g
const SKIP = new Set(['latex.css', 'katex'])

async function inline(file, seen = new Set()) {
  const absolute = path.resolve(file)
  if (seen.has(absolute)) return ''
  seen.add(absolute)

  const source = await fs.readFile(absolute, 'utf8')
  const imports = [...source.matchAll(IMPORT_RE)].map(match => match[1])
  const own = source.replace(IMPORT_RE, '').trim()

  let css = ''
  for (const specifier of imports) {
    if ([...SKIP].some(pattern => specifier.includes(pattern))) continue
    const resolved = specifier.startsWith('.')
      ? path.resolve(path.dirname(absolute), specifier)
      : require.resolve(specifier)
    css += await inline(resolved, seen)
  }
  return `${css}\n/* ${path.relative(themeDir, absolute)} */\n${own}\n`
}

const common = await inline(commonEntry)
const frame = await fs.readFile(frameEntry, 'utf8')
const dsh = await fs.readFile(overrides, 'utf8')

const css = [
  '/* Generated from @milkdown/crepe. Do not edit. */',
  common,
  '/* frame theme variables */',
  frame,
  '/* DSH overrides */',
  dsh,
].join('\n')

await fs.writeFile(output, `// Generated by scripts/generate-crepe-styles.mjs — do not edit.\nexport default ${JSON.stringify(css)}\n`)
console.log(`crepe-theme.generated.js: ${(css.length / 1024).toFixed(1)} KB of CSS`)
