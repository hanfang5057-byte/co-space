import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import brand from '../packages/brand/metadata.json' with { type: 'json' };
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'dist/site');
const repository = 'hanfang5057-byte/co-space';
const releasesUrl = `https://github.com/${repository}/releases`;
const desktopMetadata = path.join(root, 'apps/site/desktop/latest.json');

await rm(output, { recursive: true, force: true });
await mkdir(path.join(output, 'assets'), { recursive: true });
await Promise.all([
  cp(path.join(root, 'apps/site/styles.css'), path.join(output, 'styles.css')),
  cp(path.join(root, 'apps/site/site.js'), path.join(output, 'site.js')),
  cp(path.join(root, brand.icon), path.join(output, 'assets/cospace-icon.svg')),
  cp(path.join(root, 'assets/preview.png'), path.join(output, 'assets/preview.png')),
]);

// The desktop manifest is generated by the release pipeline and only updated
// after a release passed checksum, signature, and download verification, so
// its version is a safe source for direct installer links.
const desktop = await readFile(desktopMetadata, 'utf8')
  .then(text => JSON.parse(text))
  .catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
const desktopVersion = typeof desktop?.version === 'string' && /^\d+\.\d+\.\d+$/.test(desktop.version)
  ? desktop.version
  : null;

function installers() {
  if (!desktopVersion) return { dmgArm: releasesUrl, deb: releasesUrl, appimage: releasesUrl };
  const url = name => `${releasesUrl}/download/desktop-v${desktopVersion}/${encodeURIComponent(name)}`;
  return {
    dmgArm: url(`macos-arm64--CoSpace_${desktopVersion}_aarch64.dmg`),
    deb: url(`linux-x64--CoSpace_${desktopVersion}_amd64.deb`),
    appimage: url(`linux-x64--CoSpace_${desktopVersion}_amd64.AppImage`),
  };
}

const links = installers();
const replacements = {
  '{{RELEASES}}': releasesUrl,
  '{{DESKTOP_VERSION}}': desktopVersion ?? '即将发布',
  '{{DMG_ARM64}}': links.dmgArm,
  '{{DEB}}': links.deb,
  '{{APPIMAGE}}': links.appimage,
};

const source = await readFile(path.join(root, 'apps/site/index.html'), 'utf8');
const html = Object.entries(replacements)
  .reduce((text, [placeholder, value]) => text.split(placeholder).join(value), source);
if (/\{\{[A-Z_]+\}\}/.test(html)) throw new Error('The site build left an unresolved placeholder in index.html');
await writeFile(path.join(output, 'index.html'), html);

if (await stat(desktopMetadata).then(info => info.isFile()).catch(error => { if (error.code === 'ENOENT') return false; throw error; })) {
  await mkdir(path.join(output, 'desktop'), { recursive: true });
  await cp(desktopMetadata, path.join(output, 'desktop/latest.json'));
}

console.log(`Built static site at ${path.relative(root, output)}${desktopVersion ? ` with desktop ${desktopVersion} downloads` : ' without a desktop release'}`);
