/** Domain codes with a localized text; other server messages stay verbatim. */
const ERROR_KEYS = {
  REQUEST_FAILED: 'error.requestFailed',
  LIMIT_EXCEEDED: 'error.limitExceeded',
  METHOD_NOT_FOUND: 'error.methodNotFound',
  SESSION_UNAVAILABLE: 'error.sessionUnavailable',
  UNAUTHORIZED: 'error.unauthorized',
  FORBIDDEN: 'error.forbidden',
  UNAVAILABLE: 'error.unavailable',
  SEND_TARGET_UNAVAILABLE: 'send.createUnavailable',
  EDIT_REQUIRES_UNANNOTATED_DOCUMENT: 'edit.unavailable',
  VERSION_CONFLICT: 'edit.versionConflict',
};

const PLACEHOLDER = /\{([A-Za-z0-9_]+)\}/g;

/**
 * Fill `{name}` placeholders for the fallback translator used outside a locale seat.
 * @param {Record<string, string>} dict - dictionary that owns the key.
 * @param {string} key - dictionary key.
 * @param {Record<string, unknown>} [vars] - placeholder values.
 * @returns {string} translated template with its placeholders filled.
 */
export function translate(dict, key, vars) {
  const template = dict[key] ?? key;
  if (vars === undefined) return template;
  return template.replace(PLACEHOLDER, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match);
}

/**
 * Render an error for the panel, keeping server diagnostics when no localized code exists.
 * @param {unknown} error - thrown value carrying an optional `code`.
 * @param {(key: string, vars?: Record<string, unknown>) => string} t - bound translator.
 * @returns {string} localized error text.
 */
export function errorText(error, t) {
  const code = error?.code;
  const key = typeof code === 'string' ? ERROR_KEYS[code] : undefined;
  if (key !== undefined) return t(key);
  return t('error.generic', { message: error?.message || t('error.genericAction') });
}
