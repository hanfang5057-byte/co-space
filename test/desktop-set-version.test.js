import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { setDesktopVersion } from '../apps/desktop/scripts/set-version.mjs';

async function fixture(t) {
  const root = await mkdtemp(path.join(os.tmpdir(), 'cospace-set-version-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, 'apps/desktop/src-tauri'), { recursive: true });
  await writeFile(path.join(root, 'apps/desktop/package.json'), `${JSON.stringify({ name: '@cospace/desktop', version: '0.1.20' }, null, 2)}\n`);
  await writeFile(path.join(root, 'apps/desktop/adapter.json'), `${JSON.stringify({ id: 'desktop', version: '0.1.20', contractVersion: 1 }, null, 2)}\n`);
  await writeFile(path.join(root, 'apps/desktop/src-tauri/tauri.conf.json'), '{\n  "productName": "CoSpace",\n  "version": "0.1.20",\n  "plugins": { "updater": { "endpoints": ["https://example.test/latest.json"] } }\n}\n');
  await writeFile(path.join(root, 'apps/desktop/src-tauri/Cargo.toml'), [
    '[package]',
    'name = "cospace-desktop"',
    'version = "0.1.20"',
    '',
    '[dependencies]',
    'tauri = { version = "2", features = [] }',
    '',
  ].join('\n'));
  await writeFile(path.join(root, 'apps/desktop/src-tauri/Cargo.lock'), [
    '# This file is automatically @generated by Cargo.',
    '',
    '[[package]]',
    'name = "serde"',
    'version = "1.0.0"',
    '',
    '[[package]]',
    'name = "cospace-desktop"',
    'version = "0.1.20"',
    'dependencies = []',
    '',
  ].join('\n'));
  await writeFile(path.join(root, 'package-lock.json'), `${JSON.stringify({ lockfileVersion: 3, packages: { 'apps/desktop': { version: '0.1.20' } } }, null, 2)}\n`);
  return root;
}

test('setDesktopVersion updates every manifest and both lock records', async t => {
  const root = await fixture(t);
  await setDesktopVersion({ root, version: '0.1.21' });
  assert.equal(JSON.parse(await readFile(path.join(root, 'apps/desktop/package.json'), 'utf8')).version, '0.1.21');
  assert.equal(JSON.parse(await readFile(path.join(root, 'apps/desktop/adapter.json'), 'utf8')).version, '0.1.21');
  assert.equal(await readFile(path.join(root, 'apps/desktop/src-tauri/tauri.conf.json'), 'utf8'),
    '{\n  "productName": "CoSpace",\n  "version": "0.1.21",\n  "plugins": { "updater": { "endpoints": ["https://example.test/latest.json"] } }\n}\n');
  assert.equal(JSON.parse(await readFile(path.join(root, 'package-lock.json'), 'utf8')).packages['apps/desktop'].version, '0.1.21');

  const cargo = await readFile(path.join(root, 'apps/desktop/src-tauri/Cargo.toml'), 'utf8');
  assert.match(cargo, /^version = "0.1.21"$/m);
  assert.match(cargo, /tauri = \{ version = "2", features = \[\] \}/);

  const cargoLock = await readFile(path.join(root, 'apps/desktop/src-tauri/Cargo.lock'), 'utf8');
  assert.match(cargoLock, /name = "cospace-desktop"\nversion = "0.1.21"/);
  assert.match(cargoLock, /name = "serde"\nversion = "1.0.0"/);
});

test('setDesktopVersion rejects pre-release versions without writing', async t => {
  const root = await fixture(t);
  await assert.rejects(setDesktopVersion({ root, version: '0.1.21-rc.1' }), /stable semver/);
  assert.equal(JSON.parse(await readFile(path.join(root, 'apps/desktop/package.json'), 'utf8')).version, '0.1.20');
});

test('setDesktopVersion fails closed when a lock record is missing', async t => {
  const root = await fixture(t);
  const lockPath = path.join(root, 'package-lock.json');
  const lock = JSON.parse(await readFile(lockPath, 'utf8'));
  delete lock.packages['apps/desktop'];
  await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
  await assert.rejects(setDesktopVersion({ root, version: '0.1.21' }), /npm install/);
  assert.equal(JSON.parse(await readFile(lockPath, 'utf8')).packages['apps/desktop'], undefined);
  assert.equal(JSON.parse(await readFile(path.join(root, 'apps/desktop/package.json'), 'utf8')).version, '0.1.20');
});

test('setDesktopVersion fails closed on ambiguous duplicate version properties', async t => {
  const root = await fixture(t);
  const tauriPath = path.join(root, 'apps/desktop/src-tauri/tauri.conf.json');
  await writeFile(tauriPath, '{\n  "version": "0.1.20",\n  "version": "0.1.20"\n}\n');
  await assert.rejects(setDesktopVersion({ root, version: '0.1.21' }), /exactly one/);
  assert.equal(JSON.parse(await readFile(path.join(root, 'apps/desktop/package.json'), 'utf8')).version, '0.1.20');
});
