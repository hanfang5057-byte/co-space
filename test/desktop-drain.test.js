test('desktop drain refuses new sessions, preserves existing sessions, and can be cancelled', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'cospace-drain-'));
  const versionHome = path.join(root, 'version');
  await mkdir(path.join(versionHome, 'web'), { recursive: true });
  await writeFile(path.join(versionHome, 'web/index.html'), '<html><!--COSPACE_TOKEN--></html>');
  const service = await startLocalService({ dataHome: path.join(root, 'data'), runtimeHome: path.join(root, 'runtime'), versionHome });
  t.after(async () => { await service.close(); await rm(root, { recursive: true, force: true }); });
  const headers = { 'content-type': 'application/json', 'x-cospace-rpc-token': service.rpcToken };
  const post = (route, body, customHeaders = headers) => fetch(`${service.url}${route}`, { method: 'POST', headers: customHeaders, body: JSON.stringify(body) });
  assert.equal((await post('__cospace/control/upgrade', { version: '2.0.0' })).status, 404);
  assert.equal((await post('__cospace/control/updater/enable', {})).status, 404);
  const session = 'active-agent-session-123';
  assert.equal((await post('__cospace/mcp/session', { action: 'open', id: session })).status, 200);
  const deepLink = await fetch(`${service.url}?document=example`);
  assert.equal(deepLink.status, 200);
  const page = await deepLink.text();
  const uiId = page.match(/const id="([0-9a-f-]+)"/)?.[1];
  assert.ok(uiId);
  const unauthorized = await post('__cospace/control/drain', { action: 'start' }, { 'content-type': 'application/json', 'x-cospace-rpc-token': 'wrong' });
  assert.equal(unauthorized.status, 403);
  const started = await post('__cospace/control/drain', { action: 'start' });
  assert.deepEqual((await started.json()).result, { draining: true, activeMcpClients: 1, activeUiSessions: 1, inFlight: 0 });
  assert.equal((await post('__cospace/mcp/session', { action: 'open', id: 'new-agent-session-123' })).status, 503);
  assert.equal((await post('__cospace/mcp/session', { action: 'heartbeat', id: session })).status, 200);
  assert.equal((await fetch(service.url)).status, 503);
  assert.equal((await post('__cospace/mcp/session', { action: 'close', id: session })).status, 200);
  const uiHeaders = { 'content-type': 'application/json', 'x-cospace-token': service.uiToken };
  assert.equal((await post('__cospace/ui/session', { action: 'close', id: uiId }, uiHeaders)).status, 200);
  const status = await post('__cospace/control/drain', { action: 'status' });
  assert.equal((await status.json()).result.activeMcpClients, 0);
  assert.equal((await post('__cospace/control/drain', { action: 'cancel' })).status, 200);
  assert.equal((await post('__cospace/mcp/session', { action: 'open', id: 'new-agent-session-123' })).status, 200);
});

test('desktop startup recovers an abandoned drain but never clears a live update marker', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'cospace-drain-recover-'));
  const versionHome = path.join(root, 'version');
  const runtimeHome = path.join(root, 'runtime');
  const dataHome = path.join(root, 'data');
  await mkdir(path.join(versionHome, 'web'), { recursive: true });
  const service = await startLocalService({ dataHome, runtimeHome, versionHome, version: '1.0.0' });
  t.after(async () => { await service.close(); await rm(root, { recursive: true, force: true }); });
  const coordinator = createDesktopUpdateCoordinator({ ...service, runtimeHome }, '1.0.0');
  await coordinator.begin();
  await assert.rejects(recoverDesktopUpdate({ dataHome, runtimeHome, version: '1.0.0', waitMs: 0 }), { code: 'DESKTOP_UPDATE_IN_PROGRESS' });
  await coordinator.cancel();
  await fetch(`${service.url}__cospace/control/drain`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-cospace-rpc-token': service.rpcToken }, body: JSON.stringify({ action: 'start' }) });
  await writeFile(desktopUpdateFile(runtimeHome), JSON.stringify({ pid: 2147483647, version: '1.0.0' }));
  assert.equal(await recoverDesktopUpdate({ dataHome, runtimeHome, version: '1.0.0' }), true);
  assert.equal((await (await fetch(`${service.url}__cospace/health`)).json()).draining, false);
  await assert.rejects(stat(desktopUpdateFile(runtimeHome)), { code: 'ENOENT' });
});

test('desktop update lock blocks daemon starts until a cancelled drain releases it', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'cospace-desktop-lock-'));
  const versionHome = path.join(root, 'version');
  const runtimeHome = path.join(root, 'runtime');
  const dataHome = path.join(root, 'data');
  await mkdir(path.join(versionHome, 'web'), { recursive: true });
  const service = await startLocalService({ dataHome, runtimeHome, versionHome, version: '1.0.0' });
  t.after(async () => { await service.close(); await rm(root, { recursive: true, force: true }); });
  const coordinator = createDesktopUpdateCoordinator({ ...service, runtimeHome }, '1.0.0');
  const state = await coordinator.begin();
  assert.equal(state.draining, true);
  assert.ok(await stat(desktopUpdateFile(runtimeHome)));
  await assert.rejects(ensureLocalDaemon({ dataHome, runtimeHome, versionHome, version: '1.0.0', blockDuringDesktopUpdate: true }), { code: 'DESKTOP_UPDATE_IN_PROGRESS' });
  await assert.rejects(coordinator.begin(), { code: 'UPDATE_IN_PROGRESS' });
  await coordinator.cancel();
  await assert.rejects(stat(desktopUpdateFile(runtimeHome)), { code: 'ENOENT' });
  const endpoint = await ensureLocalDaemon({ dataHome, runtimeHome, versionHome, version: '1.0.0', blockDuringDesktopUpdate: true });
  assert.equal(endpoint.version, '1.0.0');
});

test('finish waits for live agents and keeps restart blocked after the daemon exits', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'cospace-drain-exit-'));
  const versionHome = path.join(root, 'version');
  const runtimeHome = path.join(root, 'runtime');
  const dataHome = path.join(root, 'data');
  await mkdir(path.join(versionHome, 'web'), { recursive: true });
  const source = `import { startLocalService } from ${JSON.stringify(new URL('../packages/local-runtime/src/service.js', import.meta.url).href)};
    const service = await startLocalService({ dataHome: process.env.TEST_DATA, runtimeHome: process.env.TEST_RUNTIME, versionHome: process.env.TEST_VERSION, version: '1.0.0' });
    console.log(JSON.stringify({ url: service.url, rpcToken: service.rpcToken }));
    process.once('SIGTERM', () => service.close().then(() => process.exit(0)));`;
  const child = spawn(process.execPath, ['--input-type=module', '-e', source], { env: { ...process.env, TEST_DATA: dataHome, TEST_RUNTIME: runtimeHome, TEST_VERSION: versionHome }, stdio: ['ignore', 'pipe', 'pipe'] });
  const lines = createInterface({ input: child.stdout });
  const exited = new Promise(resolve => child.once('exit', resolve));
  t.after(async () => { if (child.exitCode === null && child.signalCode === null) { child.kill('SIGTERM'); await exited; } lines.close(); await rm(root, { recursive: true, force: true }); });
  const endpoint = await new Promise((resolve, reject) => { lines.once('line', line => { try { resolve(JSON.parse(line)); } catch (error) { reject(error); } }); child.once('error', reject); child.once('exit', () => reject(new Error('daemon exited before readiness'))); });
  const headers = { 'content-type': 'application/json', 'x-cospace-rpc-token': endpoint.rpcToken };
  const request = (action, id) => fetch(`${endpoint.url}__cospace/mcp/session`, { method: 'POST', headers, body: JSON.stringify({ action, id }) });
  const id = 'connected-agent-session';
  assert.equal((await request('open', id)).status, 200);
  const coordinator = createDesktopUpdateCoordinator({ ...endpoint, runtimeHome }, '1.0.0');
  await coordinator.begin();
  await assert.rejects(coordinator.finish(), { code: 'SERVICE_BUSY' });
  assert.equal((await request('close', id)).status, 200);
  await coordinator.finish();
  assert.equal(await exited, 0);
  await assert.rejects(ensureLocalDaemon({ dataHome, runtimeHome, versionHome, version: '1.0.0', blockDuringDesktopUpdate: true }), { code: 'DESKTOP_UPDATE_IN_PROGRESS' });
});
